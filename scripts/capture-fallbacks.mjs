// Runs each demo preset through /api/analyse and saves the real responses to
// lib/preset-fallbacks.ts, replacing what's there. The UI shows a preset's saved
// result whenever that preset is analysed unedited.
//
// Usage: start the app (npm run dev), then in another terminal:
//   npm run capture-fallbacks                                  (uses http://localhost:3000)
//   npm run capture-fallbacks -- https://finguard-sand.vercel.app

import { readFile, writeFile } from "node:fs/promises";

const baseUrl = (process.argv[2] ?? "http://localhost:3000").replace(/\/$/, "");
const presets = JSON.parse(await readFile(new URL("../lib/presets.json", import.meta.url), "utf8"));
const outFile = new URL("../lib/preset-fallbacks.ts", import.meta.url);

const saved = {};
for (const preset of presets) {
  let status = 0;
  let data = null;
  try {
    const res = await fetch(`${baseUrl}/api/analyse`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message: preset.text.trim() }),
    });
    status = res.status;
    data = await res.json();
  } catch (err) {
    data = { error: `${err.message} (is the app running at ${baseUrl}?)` };
  }

  if (status !== 200 || typeof data?.risk_score !== "number") {
    const reason = data?.detail ?? data?.error ?? "unexpected response";
    console.log(`✗ ${preset.label}: ${status ? `HTTP ${status}, ` : ""}${reason}`);
    continue;
  }
  saved[preset.id] = data;
  console.log(`✓ ${preset.label}: ${data.risk_score} ${data.risk_level}, ${data.scam_type}`);
}

const failed = presets.length - Object.keys(saved).length;
if (failed > 0) {
  console.error(
    `\n${failed} of ${presets.length} presets failed, so lib/preset-fallbacks.ts was left unchanged.`,
  );
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
await writeFile(
  outFile,
  `// Generated by \`npm run capture-fallbacks\` on ${today}. Don't edit by hand; run it again.
// Real /api/analyse responses for the demo presets, shown when a preset is analysed unedited.
import type { Analysis } from "./analysis";

export const PRESET_FALLBACKS: Partial<Record<string, Analysis>> = ${JSON.stringify(saved, null, 2)};
`,
);
console.log(`\nSaved ${presets.length} real responses to lib/preset-fallbacks.ts`);
