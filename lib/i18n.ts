export const TRANSLATIONS: Record<LanguageCode, Dictionary> = { en, hi, kn, ml, ta, te };

// The text for a key in a language, falling back to English. {name} placeholders
// are filled from `vars`.
export function translate(
  language: LanguageCode,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const text = TRANSLATIONS[language]?.[key] ?? en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

